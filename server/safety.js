'use strict';

/**
 * 危机输入的安全边界
 * ---------------------------------------------------------------
 * 这不是心理诊断，也不试图替代专业帮助；它只做一件事：
 * 当用户明确表达自伤/轻生风险时，停止「拆任务」和「给方案」，
 * 用固定的、可读的、带有求助路径的话先接住。
 *
 * 两条硬规则：
 *   · 判断和文案都由代码给出，不交给模型自由生成；
 *   · 命中之后不调用任何外部模型（远程与 Ollama 都不调用），也不创建建议。
 *
 * 这是一条产品底线，不是可配置项。
 */

const CRISIS_RE =
  /(自杀|轻生|不想活|活不下去|活着没(意思|意义)|结束生命|想死|死了算了|伤害自己|自残|割腕|跳楼|吞药|安眠药|遗书|不想存在)/;

function detectCrisis(text) {
  return CRISIS_RE.test(String(text || ''));
}

function crisisReply() {
  return [
    '我很在意你刚才说的这些。现在先不拆任务，也不急着分析。',
    '如果你可能会伤害自己，请先联系身边可信任的人，或拨打当地急救/心理援助热线。中国大陆可以拨 110 / 120，也可以尝试当地心理援助热线（如已开通 12356）；如果你不在中国大陆，请联系当地急救电话。',
    '你现在安全吗？如果愿意，可以只回我一句「安全」或「不安全」。',
  ].join('\n\n');
}

module.exports = { detectCrisis, crisisReply };
